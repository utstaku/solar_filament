"""Build a self-contained Kaggle notebook from src/solar_filament and kernels/<name>/main.py.

    uv run python scripts/build_notebook.py kernels/classical-baseline    # -> build/classical-baseline/

The generated notebook has three parts:
  1. a note saying that it is generated and where its sources are;
  2. one `%%writefile` cell per module of the package. They become real files next to the notebook,
     so `from solar_filament.x import y` works unchanged and tracebacks carry the local line numbers;
  3. the cells of main.py, written in the percent format: a line starting with `# %%` opens a code
     cell, `# %% [markdown]` opens a markdown cell whose lines are comments.

build/<name>/ also receives kernel-metadata.json, so it can be handed to `kaggle kernels push -p`.
"""

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE_DIR = ROOT / "src" / "solar_filament"
CELL_MARKER = "# %%"


def make_cell(kind: str, text: str) -> dict:
    cell = {"cell_type": kind, "metadata": {}, "source": text.strip("\n").splitlines(keepends=True)}
    if kind == "code":
        cell.update(execution_count=None, outputs=[])
    return cell


def uncomment(line: str) -> str:
    """One line of a markdown cell: drop the leading `# `."""
    return line.removeprefix("# ") if line.startswith("# ") else line.removeprefix("#")


def percent_cells(source: str) -> list[dict]:
    """Split percent-format source into notebook cells."""
    cells, kind, lines = [], "code", []

    def flush():
        text = "\n".join(uncomment(line) for line in lines) if kind == "markdown" else "\n".join(lines)
        if text.strip():
            cells.append(make_cell(kind, text))

    for line in source.splitlines():
        if line.startswith(CELL_MARKER):
            flush()
            kind, lines = ("markdown" if "[markdown]" in line else "code"), []
        else:
            lines.append(line)
    flush()
    return cells


def package_cells() -> list[dict]:
    """`%%writefile` cells that recreate the package, preceded by a cell creating its directories."""
    modules = sorted(PACKAGE_DIR.rglob("*.py"), key=lambda p: (p.parent, p.name != "__init__.py", p.name))
    directories = sorted({m.parent.relative_to(PACKAGE_DIR.parent).as_posix() for m in modules})
    mkdir = "import os\n\n" + "\n".join(f'os.makedirs("{d}", exist_ok=True)' for d in directories)
    cells = [make_cell("code", mkdir)]
    for module in modules:
        relative = module.relative_to(PACKAGE_DIR.parent).as_posix()
        cells.append(make_cell("code", f"%%writefile {relative}\n{module.read_text()}"))
    return cells


def build(kernel_dir: Path) -> Path:
    metadata = json.loads((kernel_dir / "kernel-metadata.json").read_text())
    if metadata.get("kernel_type") != "notebook" or not metadata.get("code_file", "").endswith(".ipynb"):
        raise SystemExit(f"{kernel_dir}/kernel-metadata.json must set kernel_type=notebook and an .ipynb code_file")

    note = (
        f"> Generated by `scripts/build_notebook.py` from `kernels/{kernel_dir.name}/main.py` and "
        "`src/solar_filament/`. Edit those, not this notebook: the `%%writefile` cells below are copies."
    )
    main_cells = percent_cells((kernel_dir / "main.py").read_text())
    # keep the notebook's own title on top, then the note, then the package, then the rest
    head = main_cells[:1] if main_cells and main_cells[0]["cell_type"] == "markdown" else []
    section = make_cell(
        "markdown", "## Package `solar_filament`\n\nShared code, written to disk so it can be imported."
    )
    cells = [*head, make_cell("markdown", note), section, *package_cells(), *main_cells[len(head) :]]

    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 4,
    }
    out_dir = ROOT / "build" / kernel_dir.name
    shutil.rmtree(out_dir, ignore_errors=True)
    out_dir.mkdir(parents=True)
    (out_dir / metadata["code_file"]).write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n")
    shutil.copy(kernel_dir / "kernel-metadata.json", out_dir / "kernel-metadata.json")
    return out_dir


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: build_notebook.py <kernel-dir>")
    print(build(Path(sys.argv[1]).resolve()))
